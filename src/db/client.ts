export function generateOrderNo(prefix: string = 'ORD'): string {
  const cleanPrefix = (prefix || 'ORD').trim().replace(/[^a-zA-Z0-9_-]/g, '').toUpperCase();
  const now = new Date();
  const yyyy = now.getUTCFullYear();
  const mm = String(now.getUTCMonth() + 1).padStart(2, '0');
  const dd = String(now.getUTCDate()).padStart(2, '0');
  const rand = Math.floor(Math.random() * 0xffff)
    .toString(16)
    .toUpperCase()
    .padStart(4, '0');
  return `${cleanPrefix}-${yyyy}${mm}${dd}-${rand}`;
}

export function generateUuid(): string {
  if (typeof crypto !== 'undefined' && crypto.randomUUID) {
    return crypto.randomUUID();
  }
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0;
    const v = c === 'x' ? r : (r & 0x3) | 0x8;
    return v.toString(16);
  });
}

export interface DbClient {
  isD1: boolean;
  dialect: DbDialect;
  query<T = any>(sql: string, params?: any[]): Promise<T[]>;
  first<T = any>(sql: string, params?: any[]): Promise<T | null>;
  execute(sql: string, params?: any[]): Promise<{ changes: number; lastInsertId?: number | string }>;
  batch(operations: { sql: string; params?: any[] }[]): Promise<void>;
  raw: any;
}

/**
 * Formats a UTC cutoff timestamp for `created_at >= ?` / `< ?` comparisons.
 * Both SQLite CURRENT_TIMESTAMP and Postgres TEXT timestamps (`to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')`)
 * store 'YYYY-MM-DD HH:MM:SS' with a space separator (ASCII 0x20 < 'T' 0x54).
 */
export function formatUtcCutoff(offsetMs: number, _dialect: DbDialect = 'sqlite'): string {
  const date = new Date(Date.now() - offsetMs);
  return date.toISOString().slice(0, 19).replace('T', ' ');
}

/**
 * Translates SQLite-compatible SQL (? placeholders, datetime('now'), AUTOINCREMENT) to PostgreSQL.
 */
export function toPostgresSql(sql: string): string {
  let idx = 0;
  return sql
    .replace(/INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/datetime\s*\(\s*'now'\s*\)/gi, "to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')")
    .replace(/'(?:''|[^'])*'|(\?)/g, (match, q) => (q ? `$${++idx}` : match));
}

async function getCfEnv(): Promise<Record<string, any> | null> {
  try {
    // @ts-ignore
    const cf: any = await import('cloudflare:workers');
    return cf?.env || null;
  } catch {
    return null;
  }
}

function readRuntimeSetting(cfEnv: Record<string, any> | null, key: string): string {
  const fromCf = cfEnv && typeof cfEnv[key] === 'string' ? cfEnv[key].trim() : '';
  if (fromCf) return fromCf;
  const fromProcess = typeof process !== 'undefined' && process.env?.[key] ? String(process.env[key]).trim() : '';
  if (fromProcess) return fromProcess;
  const fromMeta = typeof import.meta !== 'undefined' && (import.meta as any).env?.[key]
    ? String((import.meta as any).env[key]).trim()
    : '';
  return fromMeta;
}

let localNodeDbInstance: any = null;

function getLocalNodeDb(): any {
  if (localNodeDbInstance) return localNodeDbInstance;
  try {
    // @ts-ignore
    const { DatabaseSync } = require('node:sqlite');
    const dbDir = path.resolve(process.cwd(), '.wrangler', 'state', 'v3', 'd1');
    if (!fs.existsSync(dbDir)) {
      fs.mkdirSync(dbDir, { recursive: true });
    }
    const dbPath = path.join(dbDir, 'local-dev.sqlite');
    localNodeDbInstance = new DatabaseSync(dbPath);
    try {
      localNodeDbInstance.exec(`
        PRAGMA journal_mode = WAL;
        PRAGMA synchronous = NORMAL;
        PRAGMA busy_timeout = 5000;
        PRAGMA foreign_keys = ON;
      `);
    } catch {}
    return localNodeDbInstance;
  } catch (err) {
    console.warn('[DB] node:sqlite initialization failed:', err);
    return null;
  }
}

class D1ClientAdapter implements DbClient {
  readonly isD1 = true;
  readonly dialect: DbDialect = 'sqlite';
  private readonly target: any;

  constructor(public readonly raw: any, sessionConstraint: string = 'first-unconstrained') {
    // If Cloudflare D1 Read Replication Sessions API is available, route reads to nearest replica while maintaining read-your-writes
    this.target = typeof raw?.withSession === 'function'
      ? raw.withSession(sessionConstraint)
      : raw;
  }

  async query<T = any>(sql: string, params: any[] = []): Promise<T[]> {
    const t0 = Date.now();
    try {
      const stmt = this.target.prepare(sql);
      const bound = params.length > 0 ? stmt.bind(...params) : stmt;
      const res = await bound.all();
      return (res?.results || []) as T[];
    } finally {
      const dur = Date.now() - t0;
      if (!sql.includes('system_error_logs')) {
        getActiveProfiler()?.addSpan('d1', dur);
        if (dur > 200) {
          console.warn(`[DB Slow SQL] query (${dur}ms): ${sql.slice(0, 160)}`);
        }
      }
    }
  }

  async first<T = any>(sql: string, params: any[] = []): Promise<T | null> {
    const t0 = Date.now();
    try {
      const stmt = this.target.prepare(sql);
      const bound = params.length > 0 ? stmt.bind(...params) : stmt;
      const res = await bound.first();
      return (res || null) as T | null;
    } finally {
      const dur = Date.now() - t0;
      if (!sql.includes('system_error_logs')) {
        getActiveProfiler()?.addSpan('d1', dur);
        if (dur > 200) {
          console.warn(`[DB Slow SQL] first (${dur}ms): ${sql.slice(0, 160)}`);
        }
      }
    }
  }

  async execute(sql: string, params: any[] = []): Promise<{ changes: number; lastInsertId?: number | string }> {
    const t0 = Date.now();
    try {
      const stmt = this.target.prepare(sql);
      const bound = params.length > 0 ? stmt.bind(...params) : stmt;
      const res = await bound.run();
      return {
        changes: res?.meta?.changes ?? 0,
        lastInsertId: res?.meta?.last_row_id,
      };
    } finally {
      const dur = Date.now() - t0;
      if (!sql.includes('system_error_logs')) {
        getActiveProfiler()?.addSpan('d1', dur);
        if (dur > 200) {
          console.warn(`[DB Slow SQL] execute (${dur}ms): ${sql.slice(0, 160)}`);
        }
      }
    }
  }

  async batch(operations: { sql: string; params?: any[] }[]): Promise<void> {
    if (!this.target || !operations || operations.length === 0) return;
    const t0 = Date.now();
    try {
      const d1Stmts = operations.map((op) => {
        const stmt = this.target.prepare(op.sql);
        return op.params && op.params.length > 0 ? stmt.bind(...op.params) : stmt;
      });
      await this.target.batch(d1Stmts);
    } finally {
      const dur = Date.now() - t0;
      if (!operations.some((op) => op.sql.includes('system_error_logs'))) {
        getActiveProfiler()?.addSpan('d1', dur);
      }
    }
  }
}

class SQLiteClientAdapter implements DbClient {
  readonly isD1 = false;
  readonly dialect: DbDialect = 'sqlite';
  private readonly statementCache = new Map<string, any>();

  constructor(public readonly raw: any) {}

  private getStatement(sql: string) {
    if (!this.raw) return null;
    let stmt = this.statementCache.get(sql);
    if (!stmt) {
      stmt = this.raw.prepare(sql);
      if (this.statementCache.size > 200) {
        const firstKey = this.statementCache.keys().next().value;
        if (firstKey) this.statementCache.delete(firstKey);
      }
      this.statementCache.set(sql, stmt);
    }
    return stmt;
  }

  async query<T = any>(sql: string, params: any[] = []): Promise<T[]> {
    if (!this.raw) return [];
    const t0 = Date.now();
    try {
      const stmt = this.getStatement(sql);
      const rows = stmt ? stmt.all(...params) : [];
      return (rows || []) as T[];
    } finally {
      if (!sql.includes('system_error_logs')) {
        getActiveProfiler()?.addSpan('d1', Date.now() - t0);
      }
    }
  }

  async first<T = any>(sql: string, params: any[] = []): Promise<T | null> {
    if (!this.raw) return null;
    const t0 = Date.now();
    try {
      const stmt = this.getStatement(sql);
      const row = stmt ? stmt.get(...params) : null;
      return (row || null) as T | null;
    } finally {
      if (!sql.includes('system_error_logs')) {
        getActiveProfiler()?.addSpan('d1', Date.now() - t0);
      }
    }
  }

  async execute(sql: string, params: any[] = []): Promise<{ changes: number; lastInsertId?: number | string }> {
    if (!this.raw) return { changes: 0 };
    const t0 = Date.now();
    try {
      const stmt = this.getStatement(sql);
      const info = stmt ? stmt.run(...params) : { changes: 0 };
      return {
        changes: Number(info?.changes ?? 0),
        lastInsertId: info?.lastInsertRowid ? String(info.lastInsertRowid) : undefined,
      };
    } finally {
      if (!sql.includes('system_error_logs')) {
        getActiveProfiler()?.addSpan('d1', Date.now() - t0);
      }
    }
  }

  async batch(operations: { sql: string; params?: any[] }[]): Promise<void> {
    if (!this.raw || !operations || operations.length === 0) return;
    this.raw.exec('BEGIN');
    try {
      for (const op of operations) {
        const stmt = this.getStatement(op.sql);
        if (stmt) stmt.run(...(op.params || []));
      }
      this.raw.exec('COMMIT');
    } catch (err) {
      try {
        this.raw.exec('ROLLBACK');
      } catch {
        // ignore rollback error on disconnected db
      }
      throw err;
    }
  }
}

class PostgresClientAdapter implements DbClient {
  readonly isD1 = false;
  readonly dialect: DbDialect = 'postgres';
  readonly raw: any;

  constructor(private readonly sqlClient: ReturnType<typeof postgres>) {
    this.raw = sqlClient;
  }

  async query<T = any>(sql: string, params: any[] = []): Promise<T[]> {
    const t0 = Date.now();
    try {
      const pgSql = toPostgresSql(sql);
      const rows = await this.sqlClient.unsafe(pgSql, params);
      return Array.from(rows) as T[];
    } finally {
      const dur = Date.now() - t0;
      if (!sql.includes('system_error_logs')) {
        getActiveProfiler()?.addSpan('d1', dur);
        if (dur > 200) {
          console.warn(`[PG Slow SQL] query (${dur}ms): ${sql.slice(0, 160)}`);
        }
      }
    }
  }

  async first<T = any>(sql: string, params: any[] = []): Promise<T | null> {
    const t0 = Date.now();
    try {
      const pgSql = toPostgresSql(sql);
      const rows = await this.sqlClient.unsafe(pgSql, params);
      return (rows[0] ?? null) as T | null;
    } finally {
      const dur = Date.now() - t0;
      if (!sql.includes('system_error_logs')) {
        getActiveProfiler()?.addSpan('d1', dur);
        if (dur > 200) {
          console.warn(`[PG Slow SQL] first (${dur}ms): ${sql.slice(0, 160)}`);
        }
      }
    }
  }

  async execute(sql: string, params: any[] = []): Promise<{ changes: number; lastInsertId?: number | string }> {
    const t0 = Date.now();
    try {
      const pgSql = toPostgresSql(sql);
      const res: any = await this.sqlClient.unsafe(pgSql, params);
      return {
        changes: Number(res?.count ?? 0),
      };
    } finally {
      const dur = Date.now() - t0;
      if (!sql.includes('system_error_logs')) {
        getActiveProfiler()?.addSpan('d1', dur);
        if (dur > 200) {
          console.warn(`[PG Slow SQL] execute (${dur}ms): ${sql.slice(0, 160)}`);
        }
      }
    }
  }

  async batch(operations: { sql: string; params?: any[] }[]): Promise<void> {
    if (!operations || operations.length === 0) return;
    const t0 = Date.now();
    try {
      await this.sqlClient.begin(async (tx: any) => {
        for (const op of operations) {
          await tx.unsafe(toPostgresSql(op.sql), op.params || []);
        }
      });
    } finally {
      const dur = Date.now() - t0;
      if (!operations.some((op) => op.sql.includes('system_error_logs'))) {
        getActiveProfiler()?.addSpan('d1', dur);
      }
    }
  }
}

let nodePgPoolCache: { connStr: string; adapter: PostgresClientAdapter } | null = null;

export function sanitizePostgresConnectionString(connStr: string): string {
  try {
    const parsed = new URL(connStr);
    // Strip Prisma/ORM-specific query params (e.g. ?pgbouncer=true) that postgres.js
    // forwards as Postgres startup GUC options and can stall Supavisor/PgBouncer poolers.
    for (const key of ['pgbouncer', 'connection_limit', 'pool_timeout', 'schema']) {
      parsed.searchParams.delete(key);
    }
    return parsed.toString();
  } catch {
    return connStr;
  }
}

function createPostgresAdapter(connStr: string, isWorkerRuntime: boolean): PostgresClientAdapter {
  const sanitizedConnStr = sanitizePostgresConnectionString(connStr);
  if (!isWorkerRuntime && nodePgPoolCache && nodePgPoolCache.connStr === sanitizedConnStr) {
    return nodePgPoolCache.adapter;
  }
  const client = postgres(sanitizedConnStr, {
    prepare: false,
    fetch_types: false,
    // Keep max >= 4 even in Workers: Promise.all across repos must not pipeline
    // Extended Queries onto a single connection (max: 1), which stalls Supavisor :6543.
    max: isWorkerRuntime ? 4 : 5,
    idle_timeout: 5,
    connect_timeout: 10,
    transform: { undefined: null },
    types: {
      bigint: {
        to: 20,
        from: [20],
        serialize: (x: number | bigint | string) => String(x),
        parse: (x: string) => {
          const n = Number(x);
          return Number.isSafeInteger(n) ? n : x;
        },
      },
    },
  });
  const adapter = new PostgresClientAdapter(client);
  if (!isWorkerRuntime) {
    nodePgPoolCache = { connStr: sanitizedConnStr, adapter };
  }
  return adapter;
}

function resolveDbProviderMode(cfEnv: Record<string, any> | null): DbProvider {
  const raw = readRuntimeSetting(cfEnv, 'DB_PROVIDER').toLowerCase();
  if (raw === 'd1' || raw === 'sqlite') return 'd1';
  if (raw === 'supabase' || raw === 'postgres' || raw === 'postgresql') return 'supabase';
  return 'auto';
}

function resolvePostgresConnectionString(cfEnv: Record<string, any> | null): string {
  const hyperdriveUrl = cfEnv?.HYPERDRIVE?.connectionString;
  if (typeof hyperdriveUrl === 'string' && hyperdriveUrl.trim()) {
    return hyperdriveUrl.trim();
  }
  return (
    readRuntimeSetting(cfEnv, 'SUPABASE_DB_URL') ||
    readRuntimeSetting(cfEnv, 'DATABASE_URL')
  );
}

export async function getActiveDbProviderInfo(): Promise<{
  provider: 'supabase' | 'd1' | 'sqlite';
  configuredMode: DbProvider;
}> {
  const cfEnv = await getCfEnv();
  const mode = resolveDbProviderMode(cfEnv);
  const pgUrl = resolvePostgresConnectionString(cfEnv);
  const runtimeD1 = cfEnv?.DB || null;

  if (mode === 'supabase' || (mode === 'auto' && Boolean(pgUrl))) {
    if (pgUrl) return { provider: 'supabase', configuredMode: mode };
  }
  if (runtimeD1) return { provider: 'd1', configuredMode: mode };
  return { provider: 'sqlite', configuredMode: mode };
}

let localSQLiteAdapterInstance: SQLiteClientAdapter | null = null;
function getLocalSQLiteAdapter(rawDb: any): SQLiteClientAdapter {
  if (!localSQLiteAdapterInstance || localSQLiteAdapterInstance.raw !== rawDb) {
    localSQLiteAdapterInstance = new SQLiteClientAdapter(rawDb);
  }
  return localSQLiteAdapterInstance;
}

const READ_ONLY_SELECT_RE = /^\s*SELECT\b/i;

function buildSqlDedupKey(op: 'query' | 'first', sql: string, params?: any[]): string {
  if (!params || params.length === 0) return `${op}:${sql}`;
  try {
    return `${op}:${sql}\0${JSON.stringify(params)}`;
  } catch {
    return `${op}:${sql}\0${String(params)}`;
  }
}

/**
 * Request-scoped database client wrapper that collapses concurrent identical
 * read-only SELECT queries within the same Request context into a single pending Promise.
 */
export class RequestDeduplicatingDbClient implements DbClient {
  private readonly inFlightReads = new Map<string, Promise<any>>();

  constructor(private readonly inner: DbClient) {}

  get isD1(): boolean {
    return this.inner.isD1;
  }

  get dialect(): DbDialect {
    return this.inner.dialect;
  }

  get raw(): any {
    return this.inner.raw;
  }

  async query<T = any>(sql: string, params: any[] = []): Promise<T[]> {
    if (!READ_ONLY_SELECT_RE.test(sql)) {
      return this.inner.query<T>(sql, params);
    }
    const key = buildSqlDedupKey('query', sql, params);
    let pending = this.inFlightReads.get(key) as Promise<T[]> | undefined;
    if (!pending) {
      pending = this.inner.query<T>(sql, params).finally(() => {
        this.inFlightReads.delete(key);
      });
      this.inFlightReads.set(key, pending);
    }
    const rows = await pending;
    return Array.isArray(rows) ? rows.slice() : rows;
  }

  async first<T = any>(sql: string, params: any[] = []): Promise<T | null> {
    if (!READ_ONLY_SELECT_RE.test(sql)) {
      return this.inner.first<T>(sql, params);
    }
    const key = buildSqlDedupKey('first', sql, params);
    let pending = this.inFlightReads.get(key) as Promise<T | null> | undefined;
    if (!pending) {
      pending = this.inner.first<T>(sql, params).finally(() => {
        this.inFlightReads.delete(key);
      });
      this.inFlightReads.set(key, pending);
    }
    const row = await pending;
    return row && typeof row === 'object' ? { ...row } : row;
  }

  async execute(sql: string, params: any[] = []): Promise<{ changes: number; lastInsertId?: number | string }> {
    this.inFlightReads.clear();
    return this.inner.execute(sql, params);
  }

  async batch(operations: { sql: string; params?: any[] }[]): Promise<void> {
    this.inFlightReads.clear();
    return this.inner.batch(operations);
  }
}

export async function getDb(): Promise<DbClient> {
  const cfEnv = await getCfEnv();
  const mode = resolveDbProviderMode(cfEnv);
  const pgUrl = resolvePostgresConnectionString(cfEnv);
  const runtimeD1 = cfEnv?.DB || null;
  const activeProfiler = getActiveProfiler() as any;

  const isWorkerRuntime = Boolean(cfEnv && Object.keys(cfEnv).length > 0);
  if (mode === 'supabase' || (mode === 'auto' && Boolean(pgUrl))) {
    if (pgUrl) {
      if (activeProfiler) {
        if (!activeProfiler._pgClient) {
          activeProfiler._pgClient = new RequestDeduplicatingDbClient(
            createPostgresAdapter(pgUrl, isWorkerRuntime)
          );
        }
        return activeProfiler._pgClient;
      }
      return createPostgresAdapter(pgUrl, isWorkerRuntime);
    }
    console.error('[DB] DB_PROVIDER=supabase is set, but HYPERDRIVE / SUPABASE_DB_URL / DATABASE_URL is missing. Falling back to D1/SQLite.');
  }

  if (runtimeD1) {
    // If running in an active request with Profiler context, reuse the D1ClientAdapter so all queries in the same request share the same D1 session bookmark (Read-Your-Writes)
    if (activeProfiler) {
      if (!activeProfiler._d1Client) {
        activeProfiler._d1Client = new RequestDeduplicatingDbClient(
          new D1ClientAdapter(runtimeD1)
        );
      }
      return activeProfiler._d1Client;
    }
    return new D1ClientAdapter(runtimeD1);
  }
  const localDb = getLocalNodeDb();
  const adapter = getLocalSQLiteAdapter(localDb);
  if (activeProfiler) {
    if (!activeProfiler._sqliteClient) {
      activeProfiler._sqliteClient = new RequestDeduplicatingDbClient(adapter);
    }
    return activeProfiler._sqliteClient;
  }
  return adapter;
}

